# מטען עם מסך ל-NP-FZ100: כל דגם שהסוללה שלו NP-FZ100
FZ100_CHARGER = '1005008267871368'


def main():
    db = json.load(open(DATA, encoding='utf-8'))
    prods = [p for p in db['products']]
    by_id = {p['id']: p for p in prods}

    # קוד סוללה לכל דגם, רק ממוצרים שנבדקו
    battery = {}
    for pid, models in BATT.items():
        p = by_id.get(pid)
        if not p or not p.get('code'):
            continue
        for m in models:
            battery.setdefault(m, p['code'])

    fz = [m for m, c in battery.items() if c == 'NP-FZ100']
    for p in prods:
        if p['collection'] == 'adapters':   # מתאמים מתויגים ב-add_adapters.py
            continue
        for k in ('for', 'models', 'brand_for', 'lens_note'):
            p.pop(k, None)
        pid = p['id']
        models = BATT.get(pid) or MODELS.get(pid) or (fz if pid == FZ100_CHARGER else None)
        if models:
            p['models'] = models
            continue
        if pid in BRAND_FOR:
            p['brand_for'] = BRAND_FOR[pid]
            p['for'] = ['M', 'D']
            if pid in LENS_NOTE:
                p['lens_note'] = LENS_NOTE[pid]
            continue
        f = FOR.get(pid, COLL_DEFAULT.get(p['collection'], []))
        if f:
            p['for'] = f

    known = {m for _, _, ms in BRANDS for m, _ in ms}
    for p in prods:
        for m in p.get('models', []):
            assert m in known, f'דגם לא מוכר: {m} ({p["id"]})'

    cams = {'types': TYPE_NAMES, 'brands': [
        {'id': bid, 'name': name, 'models': [dict(name=m, type=t, **({'battery': battery[m]} if m in battery else {})) for m, t in ms]}
        for bid, name, ms in BRANDS]}
    json.dump(cams, open(OUT, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    json.dump(db, open(DATA, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

    live = [p for p in prods if p.get('status') != 'missing']
    print('מצלמות:', sum(len(b['models']) for b in cams['brands']), '| עם סוללה בחנות:', len(battery))
    print('מוצרים מתויגים:', sum(1 for p in live if p.get('for') or p.get('models')), 'מתוך', len(live))
    for p in live:
        if not (p.get('for') or p.get('models')):
            print('  ללא תיוג:', p['id'], p['title'])


if __name__ == '__main__':
    main()
